const placeKey = (s: string): string => s.toLowerCase().replace(/[^a-z]/g, '');

const REAL = new Set(LIST.split(',').map(placeKey).filter(Boolean));

/** Is this name (a town, village, river or district, with or without "the", "River", "Upper" and the like) a well-known real place? */
export function isRealPlace(name: string): boolean {
  let s = name.trim();
  for (let prev = ''; prev !== s;) {
    prev = s;
    s = s.replace(/^(the|river|upper|lower|little|great|port|north|south|east|west|new)\s+/i, '').replace(/\s+(river|green|cross|mill|bridge|county|district)$/i, '');
  }
  return REAL.has(placeKey(name)) || REAL.has(placeKey(s));
}
